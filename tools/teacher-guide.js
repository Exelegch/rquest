// Builds docs/teacher-guide.html and docs/teacher-guide.pdf from docs/teacher-guide.template.html.
// The unit tables and Bible list come from the lessons themselves, so the guide stays up to date.
//   npm run guide
const fs = require('fs');
const path = require('path');
const { withApp, BASE } = require('./content');

const DOCS = path.join(__dirname, '..', 'docs');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const KIND = (it) => it.project ? 'Project' : it.fix ? 'Fix the bug' : it.exercise ? 'Exercises' : 'Lessons';

withApp(async ({ browser, data }) => {
  const { CONTENT, UNITS, DAILY } = data;
  const byId = Object.fromEntries(['learn', 'challenge', 'games', 'free'].flatMap(k => CONTENT[k]).map(it => [it.id, it]));

  const units = UNITS.map((u, i) => {
    const groups = {};
    for (const id of u.ids) { const it = byId[id]; if (!it) continue; (groups[KIND(it)] ||= []).push(`${it.icon} ${esc(it.title.replace(/^(Fix the bug|Project): /, ''))}`); }
    const kinds = ['Lessons', 'Exercises', 'Fix the bug', 'Project'].filter(k => groups[k]).map(k => `<b>${k}:</b> ${groups[k].join(', ')}`).join('<br>');
    return `<div class="unit" style="--u:${u.color}">
      <h3>Unit ${i + 1} · ${esc(u.en)} <span class="tag">Ages ${esc(u.age || '')}</span><span class="tag">${u.ids.length} activities</span></h3>
      <p>${esc(u.skill_en)}.</p>
      <b>By the end, children can:</b><ul>${(u.outcomes || []).map(o => `<li>${esc(o)}</li>`).join('')}</ul>
      <p class="kinds">${kinds}</p></div>`;
  }).join('\n');

  const lead = (t) => { let out = ''; for (const part of t.split(/(?<=[.!?])\s/)) { if (out.length > 110) break; out += (out ? ' ' : '') + part; } return out; };
  const where = (id) => ({ L: 'Lesson', E: 'Exercise', C: 'Challenge', G: 'Game', D: "Today's puzzle" })[id[0]] || '';
  const bible = [...Object.values(byId), ...DAILY].filter(it => it.bible || /Bible|Jesus|God|Genesis|Psalm|John \d/.test(it.prompt || ''));
  const bibleRows = bible.map(it => `<tr><td>${it.icon} ${esc(it.title)}</td><td>${where(it.id)} ${it.id}</td><td>${esc(lead(it.prompt || ''))}</td></tr>`).join('');
  const bibleTable = `<table><tr><th style="width:28%">Activity</th><th style="width:16%">Where</th><th>Starting point</th></tr>${bibleRows}</table>
    <p class="fine">Several lesson missions also use Bible words, for example "Thank you, God!" (loops), "God bless you" (functions), Bible books in ABC order (sorting) and Psalm 23:1 (cutting words).</p>`;

  const html = fs.readFileSync(path.join(DOCS, 'teacher-guide.template.html'), 'utf8')
    .replace('{{UNITS}}', units).replace('{{BIBLE}}', bibleTable)
    .replace('{{UNIT_COUNT}}', String(UNITS.length)).replace('{{CHALLENGES}}', String(CONTENT.challenge.length)).replace('{{GAMES}}', String(CONTENT.games.length))
    .replace('{{VERSION}}', new Date().toISOString().slice(0, 10)).replace('{{DATE}}', new Date().toISOString().slice(0, 10))
    .replace('Source for docs/teacher-guide.pdf. Do not edit docs/teacher-guide.html directly:', 'Generated from docs/teacher-guide.template.html by tools/teacher-guide.js. Do not edit this file:');
  fs.writeFileSync(path.join(DOCS, 'teacher-guide.html'), html);

  const page = await browser.newPage();
  await page.goto(BASE + 'docs/teacher-guide.html');
  await page.evaluate(() => document.fonts.ready);
  await page.pdf({ path: path.join(DOCS, 'teacher-guide.pdf'), format: 'A4', printBackground: true, preferCSSPageSize: true,
    displayHeaderFooter: true, headerTemplate: '<span></span>',
    footerTemplate: '<div style="width:100%;font-size:8px;color:#8A90B0;text-align:center;font-family:sans-serif">R Quest guide · page <span class="pageNumber"></span> of <span class="totalPages"></span></div>' });
  console.log('Wrote docs/teacher-guide.html and docs/teacher-guide.pdf');
}).catch((e) => { console.error(e); process.exit(1); });
